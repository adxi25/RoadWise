"""
03_prepare_dataset.py — Prepare annotated pothole images for YOLO fine-tuning.

IMPORTANT: This dataset contains NO bounding-box annotations.
This script provides TWO paths:

  Path A: You have already annotated the images (YOLO TXT format).
          The script verifies, splits and structures them for training.

  Path B: No annotations yet.
          The script generates pseudo-labels from the baseline model.
          YOU MUST REVIEW AND CORRECT pseudo-labels before training.

Usage:
  # Path A — real annotations:
  python 03_prepare_dataset.py \
      --image_dir /path/to/Pothole_Image_Data \
      --label_dir /path/to/labels \
      --output_dir datasets/roadwise_pothole \
      --seed 42

  # Path B — pseudo-labels (use with caution):
  python 03_prepare_dataset.py \
      --image_dir /path/to/Pothole_Image_Data \
      --output_dir datasets/roadwise_pothole \
      --pseudo_label_model /path/to/models/best.pt \
      --pseudo_conf 0.30 \
      --seed 42
"""

import argparse
import hashlib
import json
import logging
import random
import shutil
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger("prepare")

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".webp"}

ROADWISE_CLASS_ID = {
    "D00": 0, "D10": 1, "D20": 2, "D40": 3,
    "pothole": 3, "longitudinal": 0, "transverse": 1, "alligator": 2,
}

DATASET_YAML_TEMPLATE = """\
# RoadWise fine-tune dataset — generated by 03_prepare_dataset.py
path: {dataset_root}
train: images/train
val:   images/val
test:  images/test

nc: 4
names:
  0: D00
  1: D10
  2: D20
  3: D40

# Mapping note:
# All pothole images in this dataset are assigned class ID 3 (D40).
# The fine-tuned model remains a 4-class detector.
"""


def sha256_of_file(path: Path, block=65536) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(block):
            h.update(chunk)
    return h.hexdigest()


def group_duplicates(images: list) -> dict:
    """Return {sha256: [path, ...]} grouping."""
    from collections import defaultdict
    groups = defaultdict(list)
    for p in images:
        groups[sha256_of_file(p)].append(p)
    return dict(groups)


def create_yolo_structure(out: Path):
    for split in ("train", "val", "test"):
        (out / "images" / split).mkdir(parents=True, exist_ok=True)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)


def generate_pseudo_labels(images: list, model_path: Path, conf: float, label_out: Path):
    """Run baseline model and write YOLO .txt pseudo-labels.  Returns count written."""
    from ultralytics import YOLO
    model = YOLO(str(model_path))
    log.warning("Generating pseudo-labels with conf=%.2f — REVIEW BEFORE TRAINING.", conf)
    written = 0
    for img_path in images:
        results = model.predict(source=str(img_path), conf=conf, imgsz=640, verbose=False)
        label_path = label_out / (img_path.stem + ".txt")
        lines = []
        if results and results[0].boxes is not None:
            for box in results[0].boxes:
                cid = int(box.cls[0].item())
                # Force pothole images to class 3
                if cid not in (0, 1, 2, 3):
                    cid = 3
                x_c, y_c, w, h = box.xywhn[0].tolist()
                lines.append(f"{cid} {x_c:.6f} {y_c:.6f} {w:.6f} {h:.6f}")
        label_path.write_text("\n".join(lines))
        if lines:
            written += 1
    return written


def validate_yolo_labels(label_dir: Path, image_dir: Path):
    """Check labels match images and values are in [0,1]."""
    errors = []
    for lp in label_dir.rglob("*.txt"):
        img_candidates = [image_dir / (lp.stem + ext) for ext in IMAGE_EXTS]
        if not any(c.exists() for c in img_candidates):
            errors.append(f"Label without image: {lp.name}")
        for row in lp.read_text().strip().splitlines():
            parts = row.split()
            if len(parts) != 5:
                errors.append(f"{lp.name}: bad row '{row}'")
                continue
            try:
                cid = int(parts[0])
                vals = list(map(float, parts[1:]))
                if cid not in (0, 1, 2, 3):
                    errors.append(f"{lp.name}: class_id={cid} not in [0,3]")
                if any(v < 0 or v > 1 for v in vals):
                    errors.append(f"{lp.name}: out-of-range values {vals}")
            except ValueError:
                errors.append(f"{lp.name}: parse error '{row}'")
    return errors


def split_and_copy(image_label_pairs: list, output_dir: Path, seed: int, dev_ratio=0.7):
    """
    Split into train/val/test and copy files.
    dev_ratio: fraction going to train+val (the rest is test).
    Within dev, 85% train / 15% val.
    """
    random.seed(seed)
    random.shuffle(image_label_pairs)

    n = len(image_label_pairs)
    n_dev = int(n * dev_ratio)
    n_test = n - n_dev
    n_train = int(n_dev * 0.85)
    n_val = n_dev - n_train

    splits = {
        "train": image_label_pairs[:n_train],
        "val":   image_label_pairs[n_train:n_dev],
        "test":  image_label_pairs[n_dev:],
    }

    manifest = {"seed": seed, "splits": {}}
    for split_name, pairs in splits.items():
        manifest["splits"][split_name] = []
        for img_path, lbl_path in pairs:
            dst_img = output_dir / "images" / split_name / img_path.name
            shutil.copy2(img_path, dst_img)
            if lbl_path and lbl_path.exists():
                dst_lbl = output_dir / "labels" / split_name / (img_path.stem + ".txt")
                shutil.copy2(lbl_path, dst_lbl)
            else:
                # Empty label for unannotated images (background)
                dst_lbl = output_dir / "labels" / split_name / (img_path.stem + ".txt")
                dst_lbl.write_text("")
            manifest["splits"][split_name].append(img_path.name)

    log.info("Split: train=%d  val=%d  test=%d", n_train, n_val, n_test)
    return manifest, splits


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--image_dir", required=True)
    parser.add_argument("--label_dir", default=None,
                        help="Directory with YOLO .txt labels. Skip for pseudo-label mode.")
    parser.add_argument("--output_dir", default="datasets/roadwise_pothole")
    parser.add_argument("--pseudo_label_model", default=None,
                        help="Baseline .pt for pseudo-label generation (path B).")
    parser.add_argument("--pseudo_conf", type=float, default=0.30)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    image_dir = Path(args.image_dir)
    output_dir = Path(args.output_dir)

    images = sorted([p for p in image_dir.rglob("*") if p.suffix.lower() in IMAGE_EXTS])
    log.info("Found %d images.", len(images))

    if not images:
        log.error("No images found in %s", image_dir)
        return

    # ── Duplicate removal ─────────────────────────────────────────────────────
    log.info("Checking for duplicates…")
    hash_groups = group_duplicates(images)
    unique_images = [paths[0] for paths in hash_groups.values()]
    n_dupes = len(images) - len(unique_images)
    if n_dupes:
        log.warning("Removed %d duplicate images.", n_dupes)
    images = unique_images

    # ── Determine label source ────────────────────────────────────────────────
    label_dir = Path(args.label_dir) if args.label_dir else None
    pseudo_mode = False

    if label_dir and label_dir.exists():
        log.info("Using real annotations from: %s", label_dir)
        errors = validate_yolo_labels(label_dir, image_dir)
        if errors:
            log.warning("%d validation errors:", len(errors))
            for e in errors[:20]:
                log.warning("  %s", e)
    elif args.pseudo_label_model:
        log.warning("NO annotations found — switching to PSEUDO-LABEL mode.")
        log.warning("You MUST review pseudo-labels before training.")
        pseudo_mode = True
        label_dir = output_dir / "pseudo_labels"
        label_dir.mkdir(parents=True, exist_ok=True)
        n_written = generate_pseudo_labels(
            images, Path(args.pseudo_label_model), args.pseudo_conf, label_dir
        )
        log.info("Pseudo-labels generated for %d/%d images.", n_written, len(images))
    else:
        log.error(
            "No label_dir provided and no pseudo_label_model specified.\n"
            "This dataset has NO bounding-box annotations.\n"
            "Provide --label_dir or --pseudo_label_model to continue."
        )
        return

    # ── Build image-label pairs ───────────────────────────────────────────────
    pairs = []
    for img_path in images:
        lbl_path = label_dir / (img_path.stem + ".txt") if label_dir else None
        pairs.append((img_path, lbl_path))

    # ── Create output structure ───────────────────────────────────────────────
    create_yolo_structure(output_dir)

    manifest, splits = split_and_copy(pairs, output_dir, args.seed)

    # ── Write YAML ────────────────────────────────────────────────────────────
    yaml_content = DATASET_YAML_TEMPLATE.format(dataset_root=str(output_dir.resolve()))
    yaml_path = output_dir / "dataset.yaml"
    yaml_path.write_text(yaml_content)

    # ── Save manifest ─────────────────────────────────────────────────────────
    manifest["pseudo_label_mode"] = pseudo_mode
    manifest["total_unique_images"] = len(images)
    manifest["duplicates_removed"] = n_dupes
    manifest_path = output_dir / "split_manifest.json"
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2)

    log.info("─" * 60)
    log.info("DATASET PREPARED")
    log.info("  Output dir:    %s", output_dir)
    log.info("  dataset.yaml:  %s", yaml_path)
    log.info("  Manifest:      %s", manifest_path)
    if pseudo_mode:
        log.warning("PSEUDO-LABEL MODE: Review labels in %s before training!", label_dir)
    log.info("Next step: run 04_train.py --dataset_yaml %s", yaml_path)


if __name__ == "__main__":
    main()
